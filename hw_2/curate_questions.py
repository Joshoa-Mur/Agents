out = []
for qid, ans in KEEP.items():
    q = dict(draft[qid]); q['answer'] = ans or q['answer']
    out.append(q)
for idx, question, ans in NEW:
    c = pr[idx]
    out.append({'id': '', 'source': 'manual', 'question': question, 'answer': ans, 'evidence': c['text'],
                'doc': c['doc'], 'section': c['section'], 'page': c['page'], 'url': c['url']})
for n, q in enumerate(out, 1):
    q['id'] = f'q-{n}'; q['answerable'] = True
    assert norm(q['answer']) in norm(q['evidence']), (q['id'], q['answer'])
    assert any(has_evidence(c, q['evidence']) for c in st_all), q['id']
for n, question in enumerate(UNANSWERABLE, 1):
    out.append({'id': f'none-{n}', 'source': 'manual', 'question': question, 'answer': '', 'evidence': '',
                'doc': '', 'section': '', 'page': '', 'url': '', 'answerable': False})
# вопросы без ответа: ключевых слов нет в корпусе
full = norm(' '.join(d['text'] for d in docs))
for w in ['коап', 'казахстан', 'ozon', 'озон', 'комисси', 'горяч', 'европейск', 'авиабилет', 'упрощен', 'почта россии', 'кешбэк']:
    print(f'{w:12s} в корпусе: {w in full}')
open(HERE / 'data' / 'questions.jsonl', 'w', encoding='utf-8').write('\n'.join(json.dumps(q, ensure_ascii=False) for q in out) + '\n')
